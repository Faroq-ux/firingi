/**
 * Service visit document (Phase 68, @react-pdf/renderer): the collection / service certificate with the waste
 * transfer details (LER / EWC code, quantity, document number such as the e-GAR), parties and signature.
 * Portuguese with English second, like the other FIRINGI documents.
 */
import React from "react";
import { Document, Page, StyleSheet, Text, View, renderToBuffer } from "@react-pdf/renderer";

const s = StyleSheet.create({
  page: { padding: 32, fontSize: 9, fontFamily: "Helvetica", color: "#111827" },
  h1: { fontSize: 16, fontFamily: "Helvetica-Bold", marginBottom: 2 },
  h2: { fontSize: 11, fontFamily: "Helvetica-Bold", marginTop: 14, marginBottom: 4 },
  muted: { color: "#6b7280" },
  between: { flexDirection: "row", justifyContent: "space-between", gap: 12, marginTop: 12 },
  box: { borderWidth: 1, borderColor: "#e5e7eb", borderRadius: 4, padding: 8, flex: 1 },
  row: { flexDirection: "row", borderBottomWidth: 0.5, borderColor: "#e5e7eb", paddingVertical: 4 },
  k: { width: "40%", color: "#6b7280" },
  v: { width: "60%" },
  b: { fontFamily: "Helvetica-Bold" },
});
const dt = (d: Date | null | undefined) => (d ? new Date(d).toISOString().slice(0, 16).replace("T", " ") : "—");

export type VisitDoc = {
  number: string; service: string; isCollection: boolean; unit: string; wasteCode: string | null; date: Date; doneAt: Date | null;
  quantity: number | null; containersTaken: number | null; containersLeft: number | null; docNumber: string | null; signedBy: string | null; note: string | null;
  customer: { name: string; taxId: string | null; address: string }; provider: { name: string; taxId: string | null; licence: string | null; licenceExpires: Date | null };
  invoicedBy: "FIRINGI" | "PROVIDER"; providerInvoiceNo: string | null;
};

function Row({ k, v }: { k: string; v: string }) {
  return <View style={s.row}><Text style={s.k}>{k}</Text><Text style={s.v}>{v}</Text></View>;
}

function VisitDocument({ d }: { d: VisitDoc }) {
  return (
    <Document title={`${d.isCollection ? "Guia de recolha" : "Certificado de serviço"} ${d.number}`} author="FIRINGI">
      <Page size="A4" style={s.page}>
        <Text style={s.h1}>{d.isCollection ? "Guia de recolha de resíduos" : "Certificado de serviço"}</Text>
        <Text style={s.muted}>{d.isCollection ? "Waste collection note" : "Service certificate"} · {d.service} · FIRINGI</Text>
        <View style={s.between}>
          <View style={s.box}><Text style={s.muted}>Produtor / Producer</Text><Text style={s.b}>{d.customer.name}</Text>{d.customer.taxId ? <Text>NIF / VAT: {d.customer.taxId}</Text> : null}<Text>{d.customer.address}</Text></View>
          <View style={s.box}><Text style={s.muted}>{d.isCollection ? "Operador / Waste operator" : "Prestador / Provider"}</Text><Text style={s.b}>{d.provider.name}</Text>{d.provider.taxId ? <Text>NIF / VAT: {d.provider.taxId}</Text> : null}{d.provider.licence ? <Text>Licença / Licence: {d.provider.licence}{d.provider.licenceExpires ? ` (até / until ${d.provider.licenceExpires.toISOString().slice(0, 10)})` : ""}</Text> : null}</View>
        </View>
        <Text style={s.h2}>{d.isCollection ? "Recolha / Collection" : "Serviço / Service"}</Text>
        <Row k="Número / Number" v={d.number} />
        <Row k="Data prevista / Planned date" v={d.date.toISOString().slice(0, 10)} />
        <Row k="Realizado / Done (UTC)" v={dt(d.doneAt)} />
        {d.wasteCode ? <Row k="Código LER / EWC code" v={d.wasteCode} /> : null}
        {d.isCollection ? <Row k="Quantidade / Quantity" v={d.quantity == null ? "—" : `${d.quantity.toLocaleString("pt-PT")} ${d.unit}`} /> : null}
        {d.containersTaken != null || d.containersLeft != null ? <Row k="Contentores levados / deixados — Containers taken / left" v={`${d.containersTaken ?? "—"} / ${d.containersLeft ?? "—"}`} /> : null}
        <Row k="N.º documento de transporte (e-GAR) / Transfer document" v={d.docNumber ?? "—"} />
        <Row k="Faturação / Invoicing" v={d.invoicedBy === "FIRINGI" ? "FIRINGI" : `Prestador / Provider${d.providerInvoiceNo ? ` — ${d.providerInvoiceNo}` : ""}`} />
        {d.note ? <Row k="Observações / Notes" v={d.note} /> : null}
        <Text style={s.h2}>Assinatura / Signature</Text>
        <Text>Recebido por / Received by: {d.signedBy ?? "—"}</Text>
        <Text style={[s.muted, { marginTop: 18 }]}>Documento gerado pela FIRINGI. Para resíduos, o documento legal de transporte é a e-GAR (ou o equivalente do país); o seu número consta acima.</Text>
        <Text style={s.muted}>Generated by FIRINGI. For waste, the legal transfer document is the e-GAR (or the country&apos;s equivalent); its number is shown above.</Text>
      </Page>
    </Document>
  );
}

export async function renderVisitPdf(d: VisitDoc) {
  return renderToBuffer(<VisitDocument d={d} />);
}
